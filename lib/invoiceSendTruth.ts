// RECEIVABLES — what "Total Outstanding" counts
// ───────────────────────────────────────────────────────────────────────────

/**
 * Statuses that represent money genuinely owed to the tenant right now.
 *
 * The distinction that matters is ISSUED vs NOT ISSUED, not paid vs unpaid:
 *
 *   DRAFT     excluded — generated by closeout but still under review. Nobody
 *             has been asked for it yet, so counting it would inflate the
 *             receivable with an amount the tenant has not committed to.
 *   SENT      INCLUDED — issued and unpaid. This is the case the old
 *             PENDING-only filter got wrong: a real receivable was invisible.
 *   OVERDUE   INCLUDED — still outstanding, just late.
 *   PENDING   INCLUDED — unchanged.
 *   PAID      excluded — collected.
 *   CANCELED  excluded — never collectable.
 *
 * SENT being in this list is emphatically NOT a payment claim; it is the
 * opposite. An invoice counts as outstanding precisely BECAUSE it was issued
 * and has not been paid.
 */
export const OUTSTANDING_INVOICE_STATUSES = ['PENDING', 'SENT', 'OVERDUE'] as const;

export function isOutstandingInvoiceStatus(status: unknown): boolean {
    return typeof status === 'string'
        && (OUTSTANDING_INVOICE_STATUSES as readonly string[]).includes(status);
}

/**
 * Total currently owed to the tenant, to the cent.
 *
 * `total_amount` arrives as a Prisma Decimal serialised to a string, so each
 * value is coerced individually and the sum rounded once at the end rather than
 * relying on float addition to land clean.
 */
export function sumOutstandingInvoices(
    invoices: Array<{ status?: unknown; total_amount?: unknown }>,
): number {
    const total = invoices.reduce((sum, inv) => {
        if (!isOutstandingInvoiceStatus(inv?.status)) return sum;
        const amount = Number(inv?.total_amount);
        return Number.isFinite(amount) ? sum + amount : sum;
    }, 0);
    return Math.round((total + Number.EPSILON) * 100) / 100;
}
